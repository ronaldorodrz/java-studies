package Java.Loops;

public class ForLoop {
    public static void main(String[] args) {
        
        /* Enquanto i for menor que 5, o laço será executado.
        Após cada repetição, i será incrementado em 1. */
        System.out.println("Contagem de 0 a 4:");
        for (int i = 0; i < 5; i++) {
            System.out.println("i = " + i);
        }
    }
}
