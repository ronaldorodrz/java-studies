package Java.Loops;

public class ForEachLoop {
    public static void main(String[] args) {

        // Array de números inteiros.
        int[] numeros = {10, 20, 30, 40, 50};

        // Percorrendo todos os elementos do array.
        for (int num : numeros) {
            System.out.println(num);
        }
    }
}
