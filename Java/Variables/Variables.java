package Java.Variables;

public class Variables {
    public static void main(String[] args) {

        // String armazena texto, como "Olá"
        String nome = "Ronaldo";

        // int armazena números inteiros, sem decimais
        int ano = 2026;

        // float armazena números de ponto flutuante, com decimais
        float preco = 129.56f;

        // char armazena caracteres únicos, como 'a'
        char inicial = 'R';

        // boolean armazena valores com dois estados: verdadeiro ou falso
        boolean ceuAzul = true;

        System.out.println("Meu nome é " + nome);
        System.out.println("Estamos no ano " + ano);
        System.out.println("Este item custa " + preco);
        System.out.println("A inicial do meu nome é " + inicial);
        System.out.println("O céu é azul? " + ceuAzul);
    }
}
