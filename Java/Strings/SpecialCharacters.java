package Java.Strings;

public class SpecialCharacters {
    public static void main(String[] args) {
        /* \' Aspas simples
        Permite inserir uma aspa simples na String
        
        \" Aspas duplas
        Permite inserir aspas duplas dentro de uma String

        \\ Barra invertida (Backslash)
        Exibe uma barra invertida na String

        \n Nova linha
        Quebra a linha durante a impressão

        \t Tabulação (Tab)
        Adiciona um espaço de tabulação

        \b Backspace
        Remove o caractere imediatamente anterior

        \r Carriage Return
        Move o cursor para o início da linha

        \f Form Feed
        Avança para uma nova página */
    }
}
